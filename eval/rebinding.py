"""The adversarial edit corpus (RFC-004 §5, Part B gate).

The corpus lives in `corpora/pgmind/rebinding/*.md` — one file per category,
several cases each — and is a *deliverable*, not a fixture: it is committed,
human-readable, and meant to be extended when someone finds an edit shape that
breaks rebinding. Format and ground-truth semantics: see that directory's
README.md.

This module does three things:

- **parse** the case files (`load_cases`);
- **reindex** them — boot a vault, write every `before`/`after`, and stamp each
  case's `### index` block with the block list the parser actually produced, so
  ground truth is authored against observed ords instead of guessed ones;
- **score** a run — compare the bindings the extension actually made against
  the ground truth, per case and per category.

Scoring is deliberately two-sided. Recall (identity the engine dropped) is the
number people expect; **precision** (identity the engine handed to the wrong
block) is the one that matters more, because a wrong carry silently moves
history, citations and embeddings onto different content, and nothing
downstream can tell.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

CORPUS = Path(__file__).resolve().parent / "corpora" / "pgmind" / "rebinding"

CASE_RE = re.compile(r"^## case: ([a-z0-9][a-z0-9-]*)\s*$", re.M)
SECTION_RE = re.compile(r"^### (before|after|same|index)\s*$", re.M)
FENCE_RE = re.compile(r"^`{5}markdown\n(.*?)^`{5}\s*$", re.M | re.S)
FIELD_RE = re.compile(r"^\*\*(why|tension|ambiguous)\:\*\*\s*(.+?)\s*$", re.M)
PAIR_RE = re.compile(r"^-\s*before\[(\d+)\]\s*=>\s*after\[(\d+)\]\s*(?:#.*)?$", re.M)
NONE_RE = re.compile(r"^-\s*\(nothing carries\)\s*$", re.M)

INDEX_BANNER = "<!-- generated by `make reindex-corpus` — do not hand-edit -->"


class CorpusError(Exception):
    pass


class Case:
    def __init__(self, path: Path, name: str, body: str):
        self.file = path
        self.name = name
        self.category = path.stem
        fields = dict(FIELD_RE.findall(body))
        self.why = fields.get("why", "")
        self.tension = fields.get("tension")
        self.ambiguous = fields.get("ambiguous")
        sections = _split_sections(body)
        for required in ("before", "after", "same"):
            if required not in sections:
                raise CorpusError(f"{path.name}:{name} has no `### {required}`")
        self.before = _fenced(sections["before"], path, name, "before")
        self.after = _fenced(sections["after"], path, name, "after")
        self.same = [(int(b), int(a)) for b, a in PAIR_RE.findall(sections["same"])]
        if not self.same and not NONE_RE.search(sections["same"]):
            raise CorpusError(
                f"{path.name}:{name} has an empty `### same` — write `- (nothing carries)` "
                "to assert that on purpose"
            )
        if len(set(self.same)) != len(self.same):
            raise CorpusError(f"{path.name}:{name} repeats a pair in `### same`")
        for side, idx in (("before", 0), ("after", 1)):
            seen = [p[idx] for p in self.same]
            if len(set(seen)) != len(seen):
                raise CorpusError(
                    f"{path.name}:{name} binds one {side} block twice — identity is 1:1"
                )
        self.index = sections.get("index", "")

    @property
    def id(self) -> str:
        return f"{self.category}/{self.name}"


def _split_sections(body: str) -> dict:
    out, marks = {}, list(SECTION_RE.finditer(body))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        out[m.group(1)] = body[m.end(): end]
    return out


def _fenced(text: str, path: Path, name: str, which: str) -> str:
    m = FENCE_RE.search(text)
    if not m:
        raise CorpusError(f"{path.name}:{name} `### {which}` has no ```````markdown fence")
    return m.group(1)


def load_cases() -> list:
    cases = []
    for path in sorted(CORPUS.glob("*.md")):
        if path.name == "README.md":
            continue
        text = path.read_text()
        marks = list(CASE_RE.finditer(text))
        if not marks:
            raise CorpusError(f"{path.name} declares no cases")
        for i, m in enumerate(marks):
            end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            cases.append(Case(path, m.group(1), text[m.end(): end]))
    names = [c.id for c in cases]
    if len(set(names)) != len(names):
        raise CorpusError("duplicate case id in the corpus")
    return cases


# ---------------------------------------------------------------- observation

def blocks_of(c, db: str, path: str) -> list:
    """[(ord, kind, block_id, content, block_ref_id)] in document order."""
    raw = c.psql(db, "SELECT coalesce(json_agg(json_build_array(ord, kind, block_id::text, "
                     "content, block_ref_id) ORDER BY ord)::text, '[]') "
                     f"FROM knowledge.blocks('{path}');",
                 tuples_only=True).strip()
    return [tuple(r) for r in json.loads(raw)]


def write_note(c, db: str, path: str, source: str):
    c.psql(db, f"SELECT knowledge.write('{path}', $pgmind${source}$pgmind$::markdown);")


def observe(c, db: str, case: Case, path: str) -> dict:
    """Write `before`, then `after`, and report what the engine did with identity."""
    write_note(c, db, path, case.before)
    before = blocks_of(c, db, path)
    write_note(c, db, path, case.after)
    after = blocks_of(c, db, path)
    ord_of = {b[2]: b[0] for b in before}
    carried = {(ord_of[a[2]], a[0]) for a in after if a[2] in ord_of}
    return {"before": before, "after": after, "carried": sorted(carried)}


def classify(obs: dict, pair: tuple) -> str:
    """Which of RFC-004 A3's mechanisms *could* make this binding.

    Aggregate recall over all pairs flatters the engine badly: most blocks in a
    realistic edit are untouched, and carrying those is exact-hash bookkeeping,
    not identity resolution. Splitting the expected bindings three ways is the
    only way the number answers the question Part B is actually asking.

      identical - same content on both sides: A3 pass 2's job, free.
      marked    - content differs, both sides carry the same `^id`: pass 1's
                  job, also free, and also not inference.
      inferred  - content differs, no marker. Nothing deterministic can bind
                  it. This is the ONLY class a heuristic stage can move.
    """
    b = next(x for x in obs["before"] if x[0] == pair[0])
    a = next(x for x in obs["after"] if x[0] == pair[1])
    if b[3] == a[3] and b[1] == a[1]:
        return "identical"
    if b[4] is not None and b[4] == a[4]:
        return "marked"
    return "inferred"


def score(case: Case, obs: dict) -> dict:
    truth = set(case.same)
    carried = {tuple(p) for p in obs["carried"]}
    tp = sorted(truth & carried)
    fp = sorted(carried - truth)
    fn = sorted(truth - carried)
    # A false positive where the engine did carry that before-block, just onto
    # the wrong after-block, is the corrosive kind: history follows the ID.
    misbound = sorted(p for p in fp if any(p[0] == t[0] for t in truth))
    klass = {p: classify(obs, p) for p in truth}
    by_class = {}
    for name in ("identical", "marked", "inferred"):
        want = [p for p in truth if klass[p] == name]
        by_class[name] = {"expected": len(want),
                          "carried": sum(1 for p in want if p in carried)}
    return {
        "case": case.id, "category": case.category,
        "why": case.why, "tension": case.tension, "ambiguous": case.ambiguous,
        "expected": len(truth), "carried": len(carried),
        "tp": len(tp), "fp": len(fp), "fn": len(fn),
        "by_class": by_class,
        "misbound": misbound, "missed": fn, "spurious": [p for p in fp if p not in misbound],
        "perfect": not fp and not fn,
    }


def aggregate(rows: list) -> dict:
    """Per-category and overall precision/recall. Cases with no expected
    bindings still count: they can only lose precision, which is the point."""
    out = {}
    for key in sorted({r["category"] for r in rows}) + ["*all*"]:
        sel = rows if key == "*all*" else [r for r in rows if r["category"] == key]
        tp = sum(r["tp"] for r in sel)
        fp = sum(r["fp"] for r in sel)
        fn = sum(r["fn"] for r in sel)
        row = {
            "cases": len(sel),
            "perfect_cases": sum(1 for r in sel if r["perfect"]),
            "expected_bindings": tp + fn, "tp": tp, "fp": fp, "fn": fn,
            "recall": round(tp / (tp + fn), 4) if tp + fn else None,
            "precision": round(tp / (tp + fp), 4) if tp + fp else None,
        }
        for name in ("identical", "marked", "inferred"):
            want = sum(r["by_class"][name]["expected"] for r in sel)
            got = sum(r["by_class"][name]["carried"] for r in sel)
            row[f"recall_{name}"] = {
                "expected": want, "carried": got,
                "recall": round(got / want, 4) if want else None,
            }
        out[key] = row
    return out


# ------------------------------------------------------------------- reindex

def render_index(obs: dict) -> str:
    lines = [INDEX_BANNER, ""]
    for side in ("before", "after"):
        for ord_, kind, _id, content, ref in obs[side]:
            flat = content.replace("\n", "↵")
            if len(flat) > 64:
                flat = flat[:63] + "…"
            # Markers are stripped from `content`; without them the index cannot
            # explain why a case with `^id` claims binds the way it does.
            lines.append(f"    {side}[{ord_}] {kind:<14} {flat}" + (f"  ^{ref}" if ref else ""))
        if side == "before":
            lines.append("")
    return "\n".join(lines) + "\n"


def index_is_current(case: Case, rendered: str) -> bool:
    """Compare the committed `### index` with a freshly rendered one, ignoring
    the banner and blank-line layout — the check is about the block listing,
    not about how the file was wrapped."""
    def norm(s: str) -> list:
        return [ln.strip() for ln in s.replace(INDEX_BANNER, "").splitlines() if ln.strip()]
    return norm(case.index) == norm(rendered)


def stamp_index(case: Case, rendered: str) -> str:
    """Replace this case's `### index` section in its file. Returns the new
    file text (caller writes it) so a reindex of many cases is one write per
    file, applied in reverse order so earlier offsets stay valid."""
    text = case.file.read_text()
    marks = list(CASE_RE.finditer(text))
    start = end = None
    for i, m in enumerate(marks):
        if m.group(1) == case.name:
            start, end = m.end(), (marks[i + 1].start() if i + 1 < len(marks) else len(text))
    if start is None:
        raise CorpusError(f"{case.file.name}: case {case.name} vanished between passes")
    body = text[start:end]
    cut = body.find("### index")
    if cut >= 0:                      # `### index` is always the last section
        body = body[:cut]
    return text[:start] + body.rstrip("\n") + f"\n\n### index\n\n{rendered}\n" + text[end:]


def run_corpus(c, db: str) -> tuple:
    """Observe + score every case in one database. Each case gets its own note
    path: a rebind is a per-note operation, and sharing a path would let one
    case's history change another's outcome.

    Returns (rows, observations) — the raw observations are what the threshold
    study replays, so it studies the same residual the engine really produced."""
    rows, observations = [], []
    for case in load_cases():
        obs = observe(c, db, case, f"rebind/{case.category}/{case.name}")
        row = score(case, obs)
        row["index"] = render_index(obs)
        rows.append(row)
        observations.append((case, obs))
    return rows, observations


def main() -> int:
    """`make reindex-corpus` — stamp every case with the blocks the parser
    actually produced. Run this after editing any case's markdown; the gate
    suite fails on a stale index, because ground truth written against one is
    ground truth about a document that no longer exists."""
    from harness import cluster
    c = cluster()
    c.createdb("pgmind_reindex")
    rows = {r["case"]: r["index"] for r in run_corpus(c, "pgmind_reindex")[0]}
    touched = 0
    for case in load_cases():
        text = stamp_index(case, rows[case.id])
        if text != case.file.read_text():
            case.file.write_text(text)
            touched += 1
    print(f"reindexed {len(rows)} cases in {len(set(c.file for c in load_cases()))} files "
          f"({touched} file writes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
